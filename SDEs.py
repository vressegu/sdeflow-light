### Reverse SDE
def sample_rademacher(shape, device):
    return (torch.rand(*shape,device=device).ge(0.5)).float() * 2 - 1

def sample_gaussian(shape, device):
    return torch.randn(*shape, device=device)

def randu_on_sphere(shape, device): 
    # Let X_i be N(0,1) and  lambda^2 =2 sum X_i^2, then (X_1,...,X_d) / lambda  is uniform in S^{d-1}
    X = torch.randn(*shape,device=device)
    X_norm = torch.linalg.norm(X, dim = 1).reshape(shape[0],1)
    X =  X / X_norm 
    # del X_norm
    return X

def sample_v(shape, device, vtype='rademacher'):
    if vtype == 'rademacher':
        return sample_rademacher(shape, device=device)
    elif vtype == 'normal' or vtype == 'gaussian':
        return sample_gaussian(shape, device=device)
    elif vtype == 'uniform' :
        return randu_on_sphere(shape, device=device)
    else:
        Exception(f'vtype {vtype} not supported')

class PluginReverseSDE(torch.nn.Module):
    """
    inverting a given base sde with drift `f` and diffusion `g`, and an inference sde's drift `a` by
    f <- g a - f
    g <- g
    (time is inverted)
    """
    def __init__(self, base_sde, drift_a, T, vtype='rademacher', debias=False, ssm_intT=False, deviceReverseSDE='cpu', n_slices=1):
        super().__init__()
        self.base_sde = base_sde.to(deviceReverseSDE)
        self.a = drift_a
        self.T = T.to(deviceReverseSDE)
        self.vtype = vtype
        self.ssm_intT = ssm_intT
        self.debias = debias
        self.deviceReverseSDE = deviceReverseSDE
        # number of independent Hutchinson projections averaged per SSM loss
        # evaluation: reduces the trace estimator's variance ~1/n_slices at
        # the cost of n_slices extra vector-Jacobian products. Since the
        # SPDE's own time integration (num_steps_forward RK4 steps) dominates
        # cost, a larger n_slices (e.g. sqrt(d) = npixel) is cheap relatively.
        self.n_slices = n_slices

    # Drift
    def mu(self, t, y, lmbd=0.):
        return self.ga_m_drift(self.T-t, y, lmbd)

    # Drift of reserve generative SDE
    def ga_m_drift(self, s, y, lmbd=0.):
        return (1. - 0.5 * lmbd) * self.ga(s, y) - self.base_sde.f(s, y) + (1. - lmbd) * self.base_sde.div_Sigma(s, y)

    def _eval_a(self, y, s):
        """
        Evaluate the score network a(). a(x_t) plays the same structural
        role as the SDE's noise dBt: real, one scalar per mode, regardless
        of whether y itself is real (dense/non-FFT case) or the complex
        Fourier state (FFTfields, y: (B,n,2)). For FFTfields, a()'s own
        FFTfield=True handles the ifft2 conversion of y to the spatial image
        the network natively operates on, but always returns a real (B,n)
        result (never re-FFT'd -- see VorticityUNet.forward's docstring),
        matching how ga() must combine a with g: by scaling g's own (re,im)
        channels with the real aK, never by treating a itself as complex.
        """
        if y.dim() == 3 and y.shape[-1] == 2:
            return self.a(y, s, FFTfield=True)
        return self.a(y, s)

    def ga(self, s, y, return_a=False):
        """
        Computes g(y)*a(y). y may be Fourier-domain flat (B,n,2) -- the
        representation ga_m_drift/mu (the reverse-SDE sampling path) use --
        or spatial-domain flat (B,n) -- what ssm_loss passes for FFTfields
        (see ssm()); the result is returned in that same representation,
        and a is also returned when return_a=True (ssm_loss needs it for
        mNu).

        a(x_t) plays the same structural role as the noise dBt in the
        forward SDE (dx_t = G(x_t) o dBt): a() itself always stays real,
        one scalar per pixel, spatial (see _eval_a/VorticityUNet.forward).
        For AMSGM, the true noise is 2-dimensional per mode (dB^R_t(k),
        dB^I_t(k) -- see transportNoise.grid_k.build_sparse_G), so a's own
        FFT (Hermitian-symmetric, like any real field's) supplies the
        matching 2 channels: a_fft[...,0] pairs with G^R, a_fft[...,1]
        pairs with G^I -- never by converting a itself to Fourier/complex
        the way y is (that would introduce spurious re*im cross terms).
        This mirrors exactly how EMstep (sde_scheme.py) broadcasts the two
        real dW_R/dW_I across sigma_R/sigma_I.
        """
        is_fourier = (y.dim() == 3 and y.shape[-1] == 2)
        y_fft = y if is_fourier else spatial_flat_to_fourier(y)
        g = self.base_sde.g(s, y_fft, self.base_sde.sparseTensor)
        a = self._eval_a(y, s.squeeze())                # (B,n) always real, spatial
        if self.base_sde.sparseTensor:
            I, J, K = self.base_sde.IJK()
            if self.base_sde.AMSGM:
                g_R, g_I = g
                a_fft = spatial_flat_to_fourier(a)          # (B,n,2): channels match dB^R/dB^I per mode
                aK_R = mps_safe_gather(a_fft[..., 0], 1, K)
                aK_I = mps_safe_gather(a_fft[..., 1], 1, K)
                prod = g_R * aK_R.unsqueeze(-1) + g_I * aK_I.unsqueeze(-1)  # (B,nnz,2)
            else:
                aK = mps_safe_gather(a, 1, K)                   # (B,nnz) real
                if g.dim() > aK.dim():
                    aK = aK.unsqueeze(-1)      # broadcast the real scalar across g's (re,im) channels
                prod = g * aK                # (B,nnz) or (B,nnz,2)
            dx_fft = torch.zeros(y_fft.shape[0], y_fft.shape[1], *y_fft.shape[2:], device=y_fft.device, dtype=prod.dtype)
            index = I.unsqueeze(0).expand(y_fft.shape[0], -1)
            if prod.dim() > 2:
                index = index.unsqueeze(-1).expand(-1, -1, prod.shape[-1])
            mps_safe_scatter_add_(dx_fft, 1, index, prod)
        else:
            # g is either a dense (B,n,n) diffusion matrix (needs a matvec via
            # einsum), or an elementwise/diagonal diffusion coefficient the
            # same shape as `a` (just multiply).
            if g.shape == a.shape:
                dx_fft = g * a
            else:
                dx_fft = torch.einsum('bij, bj -> bi', g, a)
        dx = dx_fft if is_fourier else fourier_flat_to_spatial(dx_fft)
        return (dx, a) if return_a else dx


    # Stratonovich Drift
    def mu_Strato(self, t, y, lmbd=0.):
        return self.mu(t, y, lmbd) - 0.5 * (1. - lmbd) * self.base_sde.div_Sigma(self.T-t, y)

    # Diffusion
    def sigma(self, t, y, lmbd=0., sparse=False):
        g = self.base_sde.g(self.T-t, y, sparse)
        scale = (1. - lmbd) ** 0.5
        if isinstance(g, tuple):
            return tuple(scale * gi for gi in g)
        return scale * g

