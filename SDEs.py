    @torch.enable_grad()
    def ssm(self, x):
        """
        estimating the SSM loss of the plug-in reverse SDE
        """
        t_,x,y = self.sample_txy(x)
        if self.base_sde.FFTfields and y.dim() == 3 and y.shape[-1] == 2:
            y = fourier_flat_to_spatial(y)   # differentiate w.r.t. the spatial state, see ga()
        y.requires_grad_()
        return self.ssm_loss(t_,x,y)

    def _hutchinson_trace(self, mu_to_div, y, batch_size):
        """
        Averages self.n_slices independent Hutchinson projections of
        mu_to_div's divergence w.r.t. y, reducing the (unbiased) trace
        estimator's variance by ~1/n_slices. All calls share the same
        mu_to_div/y computation graph (retain_graph=True throughout, since
        it must survive n_slices vector-Jacobian products, not just one).
        """
        mMu_slices = []
        for i in range(self.n_slices):
            with torch.no_grad():
                v = sample_v(y.shape, vtype=self.vtype, device=self.deviceReverseSDE).to(y)
            retain = self.training or (i < self.n_slices - 1)
            grad_i = torch.autograd.grad(mu_to_div, y, v, create_graph=self.training, retain_graph=retain)[0]
            mMu_slices.append((grad_i * v).reshape(batch_size, -1).sum(1, keepdim=False))
        return torch.stack(mMu_slices, dim=0).mean(0)

    def _mu_to_div_and_a(self, t_, y):
        """
        Computes (mu_to_div, a) for the SSM loss.
        mu_to_div = ga(t,y) - f(t,y) + 0.5*div_Sigma(t,y) always (this is
        ga_m_drift(t,y,0.) - 0.5*div_Sigma(t,y) simplified -- see ga_m_drift).
        y may be spatial (B,n, FFTfields) or Fourier (B,n,2, otherwise);
        ga() handles both directly. f/div_Sigma are Fourier-domain-only
        operators, so for spatial y they're evaluated on its Fourier
        conversion and brought back to spatial to match.
        """
        ga_val, a = self.ga(t_, y, return_a=True)
        if y.dim() == 2:
            y_fft = spatial_flat_to_fourier(y)
            f = fourier_flat_to_spatial(self.base_sde.f(t_, y_fft))
            div_sigma = fourier_flat_to_spatial(self.base_sde.div_Sigma(t_, y_fft))
        else:
            f = self.base_sde.f(t_, y)
            div_sigma = self.base_sde.div_Sigma(t_, y)
        mu_to_div = ga_val - f + 0.5 * div_sigma
        return mu_to_div, a

    @torch.enable_grad()
    def ssm_loss(self, t_, x, y):
        """
        estimating the SSM loss of the plug-in reverse SDE by estimating div(mu) using the Hutchinson trace estimator
        """
        mu_to_div, a = self._mu_to_div_and_a(t_, y)
        mMu = self._hutchinson_trace(mu_to_div, y, x.size(0))
        if self.base_sde.AMSGM:
            # noise is 2-dim per mode (dB^R_t(k), dB^I_t(k)); a's own FFT
            # supplies the matching 2 channels (see ga()'s docstring)
            a_nu = spatial_flat_to_fourier(a)
        else:
            a_nu = a
        mNu = (a_nu ** 2).reshape(x.size(0), -1).sum(1, keepdim=False) / 2
        return mMu + mNu

    def sample_txy(self, x):
        """
        sampling t,x,y
        """
        with torch.no_grad():
            if self.ssm_intT:
                # GRIDDED t uniformly between [0, T], truncated at t_epsilon
                batchsize = x.shape[0]
                dim = x.shape[1]
                t_, mask_le_t_eps = self.sample_t_linspace(x)
                y = self.base_sde.sample_scheme_allt(x, 
                                                     keep_all_samples=True,
                                                     include_t0=False)
                y = y[~mask_le_t_eps,:,:]

                # n_subsample = 4
                # t_ = t_[0:-1:n_subsample]  # subsample in time
                # y = y[0:-1:n_subsample,:,:]

                if any(mask_le_t_eps):
                    print(str((100*mask_le_t_eps.sum().item()/mask_le_t_eps.shape[0])) + '%' + ' of time steps are truncated at t_epsilon')

                num_steps = t_.shape[0]
                t_ = t_[:,None].repeat(1, batchsize)
                x = x[None,:,:].repeat(num_steps,1,1)

                t_ = t_.reshape((batchsize*num_steps,1))
                x = x.reshape((batchsize*num_steps,dim))
                y = y.reshape((batchsize*num_steps,dim))
                # WARNING order='F' IS NOT USED 
            else:
                # sampling t uniformly between [0, T], truncated at t_epsilon
                t_ = self.sample_t(x)
                y = self.base_sde.sample(t_, x)
        return t_,x,y

    def sample_t(self, x):
        """
        sampling t uniformly between [0, T], truncated at t_epsilon
        """
        t_ = torch.rand([x.size(0), ] + [1 for _ in range(x.ndim - 1)]).to(x) * self.T

        # truncated at t_epsilon for t < t_epsilon
        mask_le_t_eps = (t_ <= self.base_sde.t_epsilon).float()
        t_ = mask_le_t_eps * self.base_sde.t_epsilon + (1. - mask_le_t_eps) * t_
        return t_
    
    def sample_t_linspace(self, x):
        """
        GRIDDED t uniformly between [0, T]
        """
        dt = self.T / self.base_sde.num_steps_forward
        t_ = torch.linspace(dt[0], self.T[0], self.base_sde.num_steps_forward ).to(device)

        # truncated at t_epsilon for t < t_epsilon
        mask_le_t_eps = (t_ <= self.base_sde.t_epsilon)
        t_ = t_[~mask_le_t_eps]
        
        return t_,mask_le_t_eps
    
    def elbo_random_t_slice(self, x):
        """
        estimating the ELBO of the plug-in reverse SDE by sampling t uniformly between [0, T], and by estimating
        div(mu) using the Hutchinson trace estimator
        """

        qt = 1 / self.T
        loss_ssm = self.ssm(x)/ qt

        t_,x,y = self.sample_txy(x)
        yT = self.cond_latent_sample(t_, self.base_sde.T, x)
        lp = self.base_sde.log_latent_pdf(yT).reshape(x.size(0), -1).sum(1)

        return lp - loss_ssm
    
